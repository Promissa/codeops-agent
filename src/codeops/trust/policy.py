"""Independent filesystem, outbound, write, and command boundaries."""

import json
from pathlib import Path, PurePosixPath
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from codeops.safety.command_policy import CommandPolicy


POLICY_PATH = Path(".codeops/trust_policy.yaml")
HARD_READ_DENIES = (
    "**/.env", "**/.env.*", "**/.env*", "**/id_rsa*", "**/id_ed25519*", "**/*.pem",
    "**/*.key", "**/.ssh", "~/.ssh/**", "**/.git",
    "**/.codeops/evolution", "**/.codeops/trust_policy.yaml", "**/.codeops/llm.yaml",
)
DEFAULT_READ_DENIES = (
    *HARD_READ_DENIES, "**/.codeops", "**/.codegraph", "**/.runs", "**/.venv",
    "**/.aws", "**/.gnupg", "**/.git-credentials", "**/.netrc", "**/__pycache__",
    "**/.pytest_cache", "**/node_modules",
)
DEFAULT_OUTBOUND_DENIES = (
    *DEFAULT_READ_DENIES, "**/logs", "**/*.log", "**/*.log.*", "**/*.out",
    "**/*.err", "**/*.local", "**/*.local.*", "**/local.*", "**/.npmrc",
    "**/.pypirc", "**/.gitconfig", "**/config", "**/config.*",
)

SandboxMode = Literal["none", "bwrap"]


class WriteBudget(BaseModel):
    model_config = ConfigDict(extra="forbid")

    max_files_changed: int = Field(default=3, ge=0)
    max_loc_changed: int = Field(default=120, ge=0)
    allow_dependency_change: bool = False
    allow_public_api_change: bool = False


class SandboxConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    backend: SandboxMode = "bwrap"
    network_enabled: bool = False
    tmpfs_size_mb: int = Field(default=256, gt=0)
    workspace_quota_mb: int = Field(default=1024, gt=0)
    timeout_seconds: int = Field(default=120, gt=0)


class TrustPolicy(BaseModel):
    model_config = ConfigDict(extra="forbid")

    confirmed: bool = False
    read_allow_globs: list[str] = Field(default_factory=lambda: ["**"])
    read_deny_globs: list[str] = Field(default_factory=lambda: list(DEFAULT_READ_DENIES))
    outbound_allow_globs: list[str] = Field(default_factory=list)
    outbound_deny_globs: list[str] = Field(
        default_factory=lambda: list(DEFAULT_OUTBOUND_DENIES)
    )
    write_budget: WriteBudget = Field(default_factory=WriteBudget)
    sandbox: SandboxConfig = Field(default_factory=SandboxConfig)
    allowed_test_commands: list[list[str]] = Field(default_factory=list)
    escalation_budget: int = Field(default=2, ge=0)

    @field_validator("allowed_test_commands")
    @classmethod
    def validate_commands(cls, commands: list[list[str]]) -> list[list[str]]:
        for command in commands:
            result = CommandPolicy().validate(command)
            if not result.allowed:
                raise ValueError(result.reason)
        return commands

    @property
    def effective_read_denies(self) -> list[str]:
        return list(dict.fromkeys([*HARD_READ_DENIES, *self.read_deny_globs]))

    def denies_read(self, path: str) -> bool:
        return not _valid_relative(path) or _matches_ancestor(path, self.effective_read_denies)

    def permits_read(self, path: str) -> bool:
        return not self.denies_read(path) and _matches(path, self.read_allow_globs)

    @property
    def effective_outbound_denies(self) -> list[str]:
        return list(dict.fromkeys([*HARD_READ_DENIES, *self.outbound_deny_globs]))

    def permits_outbound(self, path: str) -> bool:
        # Read and outbound grants are independent. Hard secrets stay local.
        return not self.denies_outbound(path) and _matches(path, self.outbound_allow_globs)

    def denies_outbound(self, path: str) -> bool:
        return not _valid_relative(path) or _matches_ancestor(path, self.effective_outbound_denies)

    def to_yaml(self) -> str:
        # JSON is valid YAML 1.2 and keeps the generated policy portable
        # even in the base install, which has no YAML parser.
        return self.model_dump_json(indent=2) + "\n"

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.to_yaml(), encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> "TrustPolicy":
        return cls.parse(path.read_text(encoding="utf-8"))

    @classmethod
    def parse(cls, contents: str) -> "TrustPolicy":
        try:
            return cls.model_validate(json.loads(contents))
        except json.JSONDecodeError:
            try:
                import yaml
            except ImportError as exc:
                raise ValueError("Use the JSON-compatible YAML generated by trust-init.") from exc
            try:
                return cls.model_validate(yaml.safe_load(contents))
            except yaml.YAMLError as exc:
                raise ValueError(f"Invalid trust policy YAML: {exc}") from exc


def _valid_relative(path: str) -> bool:
    parts = PurePosixPath(path).parts
    return bool(parts) and not (
        path.startswith(("/", "~")) or ".." in parts or "\\" in path
    )


def _matches(path: str, patterns: list[str] | tuple[str, ...]) -> bool:
    candidate = PurePosixPath(path)
    for pattern in patterns:
        while pattern.startswith("**/"):
            if candidate.full_match(pattern):
                return True
            pattern = pattern[3:]
        if pattern and candidate.full_match(pattern):
            return True
    return False


def _matches_ancestor(path: str, patterns: list[str] | tuple[str, ...]) -> bool:
    candidate = PurePosixPath(path)
    return any(
        _matches(item.as_posix(), patterns)
        for item in (candidate, *candidate.parents)
        if item.parts
    )
